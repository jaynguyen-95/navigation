/* translated text for a record: the guest's language when filled in, otherwise the default text */
const LT = (o, f) => { if (!o) return ''; const t = o.tr && o.tr[LANG]; return t && typeof t[f] === 'string' && t[f].trim() ? t[f] : (o[f] || ''); };
function cleanTr(tr, fields){
  const out = {};
  if (!tr || typeof tr !== 'object') return out;
  for (const c of LANG_CODES){
    const t = tr[c]; if (!t || typeof t !== 'object') continue;
    const o = {}; let any = false;
    for (const f of fields){ const v = typeof t[f] === 'string' ? t[f].trim() : ''; if (v){ o[f] = v; any = true; } }
    if (any) out[c] = o;
  }
  return out;
}
